export function getGeoPageData(
  serviceType: string,
  slug: string
): GeoPageData | undefined {
  const pages = ALL_GEO_PAGES[serviceType];
  if (!pages) return undefined;
  return pages.find((p) => p.slug === slug);
}

export function getAllGeoPagesByType(serviceType: string): GeoPageData[] {
  return ALL_GEO_PAGES[serviceType] ?? [];
}

export function getAllGeoSlugs(serviceType: string): string[] {
  return (ALL_GEO_PAGES[serviceType] ?? []).map((p) => p.slug);
}
